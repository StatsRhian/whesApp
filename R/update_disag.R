#' List possible disaggregations for an indicator
#'
#' @param indicator_list Data frame containing the disaggregations for
#' each indicator.
#' @inheritParams update_disag1_input
#' @return Character vector of the disaggregation options
get_disag_choices = function(selected_ind_id,
                             indicator_list = whesApp::indicator_info) {
  indicator_list %>%
    dplyr::filter(.data$ind_id == .env$selected_ind_id) %>%
    dplyr::pull(.data$disag) %>%
    unlist()
}

#' Count how many disaggregations are available
#'
#' A disaggregation label of "None" is not counted towards the final total,
#' and a return value of 2 represents two _or more_ disaggregations available.
#' @inheritParams update_disag1_input
#' @return Integer with value 0, 1, or 2, listing the number of non-"None"
#' disaggregation labels. 2 represents two _or more_ disaggregations available.
count_available_disag = function(disag_choices,
                                 selected_ind_id,
                                 selected_disag) {
  no_disag_avail = (length(disag_choices) == 1) & (disag_choices[[1]] == "None")
  second_disag_avail = is_second_allowed(selected_ind_id, selected_disag)
  single_disag_only = ((length(disag_choices) == 2) & ("None" %in% disag_choices)) |
    (!second_disag_avail & !no_disag_avail)

  if (sum(c(no_disag_avail, second_disag_avail, single_disag_only) == TRUE) != 1) {
    stop("Problem with disaggregate checks.")
  }

  return(
    dplyr::case_when(
      no_disag_avail ~ 0L,
      single_disag_only ~ 1L,
      TRUE ~ 2L
    )
  )
}

update_disag_input = function(disag, choices, selected, lang) {
  session = shiny::getDefaultReactiveDomain()

  label = dplyr::case_when(
    disag == "disag" ~ "select_disag_1_label",
    disag == "disag2" ~ "select_disag_2_label"
  )

  shiny::updateSelectInput(
    session,
    inputId = disag,
    label = tr_pull(label, lang),
    choices = tr_deframe(pattern = choices, lang = lang),
    selected = tr_deframe(pattern = selected, lang = lang)
  )
}

#' Update primary disag input
#'
#' @param selected_ind_id The current selected indicator
#' @param disag_choices Character vector of disaggregation choices, usually
#' generated by [get_disag_choices()].
#' @param disag_count Integer representing number of available disaggregations
#' usually provided by [count_available_disag()]
#' @param selected_output_type Character string denoting whether the user is
#' viewing an infographic, barchart or table?
#' @param selected_disag Current value of the primary disag - "None", "Age",
#' "Gender", "Education" or "Deprivation".
#' @param lang The language code, either "EN" or "CY"
#' @return This method is usually called for its side-effect. The
#' input$disag input will be updated with new choices.
update_disag1_input = function(selected_ind_id,
                               disag_choices,
                               disag_count,
                               selected_output_type,
                               selected_disag,
                               lang) {
  if ((selected_output_type == "infographic" &&
       (is_percent(selected_ind_id) &&
        disag_count > 0L)) ||
      (selected_output_type != "infographic" &&
       disag_count > 0L)) {
    shinyjs::enable("disag")
    set_disag1_to_choices(selected_disag, disag_choices, lang)
  } else {
    shinyjs::disable("disag")
    update_disag_input("disag", "disaggregate_None", "disaggregate_None", lang)
  }
}

#' Update secondary disag input
#'
#' @inheritParams update_disag1_input
#' @return This method is usually called for its side-effect. The
#' input$disag2 input will be updated with new choices.
update_disag2_input = function(disag_choices,
                               disag_count,
                               selected_output_type,
                               selected_disag,
                               lang) {
  if (selected_output_type != "infographic" && disag_count >= 2L) {
    shinyjs::enable("disag2")
    set_disag2_to_choices(selected_disag, disag_choices, lang)
  } else {
    shinyjs::disable("disag2")
    update_disag_input("disag2", "disaggregate_None", "disaggregate_None", lang)
  }
}

set_disag1_to_choices = function(selected_disag, disag_choices, lang) {

  # Often, we want to set the selected disag to either the current disag, or "None"
  search_disag = glue::glue("disaggregate_({paste(disag_choices, collapse = '|')})")
  if (selected_disag %in% disag_choices) {
    update_disag_input("disag", search_disag, glue::glue("disaggregate_{selected_disag}"), lang)
  } else {
    update_disag_input("disag", search_disag, "disaggregate_None", lang)
  }
}

set_disag2_to_choices = function(selected_disag, disag_choices, lang) {
  disag_choices_2 = disag_choices[disag_choices != selected_disag]
  search_disag = glue::glue("disaggregate_({paste(disag_choices_2, collapse = '|')})")
  update_disag_input("disag2", search_disag, "disaggregate_None", lang)
}

is_second_allowed = function(selected_ind_id, selected_disag) {
  if (selected_disag == "None") {
    return(FALSE)
  }
  whesApp::indicator_data %>%
    dplyr::filter(.data$ind_id == selected_ind_id) %>%
    dplyr::filter(!!rlang::sym(selected_disag) != "All") %>%
    dplyr::select(!!whesApp::breakdown_vars) %>%
    dplyr::select(-!!selected_disag) %>%
    purrr::map_lgl(is_all) %>%
    all() %>%
    isFALSE()
}

is_all = function(x) {
  all(x == "All")
}
